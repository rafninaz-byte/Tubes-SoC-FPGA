
module tb_nna;

    // ===============================
    // Clock & Control
    // ===============================
    reg clk;
    reg rst;
    reg start;

    // ===============================
    // NN Inputs (INT8)
    // ===============================
    reg signed [7:0] x0, x1, x2, x3;

    // ===============================
    // Outputs
    // ===============================
    wire [1:0] class_id;
    wire neuron_done;
    wire [2:0] LED;

    // ===============================
    // Clock generation (50 MHz)
    // ===============================
    initial begin
        clk = 0;
        forever #10 clk = ~clk;   // 20 ns period
    end

    // ===============================
    // DUT
    // ===============================
    NNA_TOP dut (
        .clk(clk),
        .rst(rst),
        .start(start),

        .x0(x0),
        .x1(x1),
        .x2(x2),
        .x3(x3),

        .class_id(class_id),
        .neuron_done(neuron_done),
        .LED(LED)
    );

    // ===============================
    // Test sequence
    // ===============================
    initial begin
        // ---------------------------
        // Init
        // ---------------------------
        rst   = 1'b1;
        start = 1'b0;

        x0 = 0; x1 = 0; x2 = 0; x3 = 0;

        #100;
        rst = 1'b0;

        // ===========================
        // TEST 1
        // ===========================
        x0 = 8'sd13;
        x1 = 8'sd76;
        x2 = 8'sd24;
        x3 = 8'sd82;

        #20;
        start = 1'b1;
        #20;
        start = 1'b0;

        wait(neuron_done);
        #20;


        // ===========================
        // TEST 2
        // ===========================
        x0 = 8'sd80;
        x1 = 8'sd10;
        x2 = 8'sd5;
        x3 = 8'sd2;

        #20;
        start = 1'b1;
        #20;
        start = 1'b0;

        wait(neuron_done);
        #20;


        // ===========================
        // TEST 3
        // ===========================
        x0 = 8'sd5;
        x1 = 8'sd15;
        x2 = 8'sd100;
        x3 = 8'sd40;

        #20;
        start = 1'b1;
        #20;
        start = 1'b0;

        wait(neuron_done);
        #20;


        // ===========================
        // End
        // ===========================
        #100;
        $stop;
    end

endmodule
